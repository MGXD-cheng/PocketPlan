"""Generate the GBK <-> Unicode table used by PocketPlan.

The TF card is formatted with Chinese file names.  ESP-IDF's FatFS with
CONFIG_FATFS_CODEPAGE_936 hands them back as GBK bytes, while LVGL and HTTP both
speak UTF-8, so the firmware needs a conversion table.  Emitting it from
Python's own cp936 codec keeps it exactly in sync with the real standard.
"""

OUT = r"D:\Users\PC\Desktop\esp32-mgxd\pocketplan\main\gbk_table.h"

LEADS = range(0x81, 0xFF)
TRAILS = [t for t in range(0x40, 0xFF) if t != 0x7F]

rows = []
count = 0
for lead in LEADS:
    cells = []
    for trail in TRAILS:
        try:
            ch = bytes([lead, trail]).decode("cp936")
            assert len(ch) == 1
            cells.append(ord(ch))
            count += 1
        except Exception:
            cells.append(0xFFFF)  # unmapped slot
    rows.append((lead, cells))

lines = []
lines.append("/* Auto-generated by tools/gen_gbk_table.py -- do not edit. */")
lines.append("#pragma once")
lines.append("#include <stdint.h>")
lines.append("")
lines.append("#define GBK_LEAD_MIN 0x81")
lines.append("#define GBK_LEAD_MAX 0xFE")
lines.append("#define GBK_TRAIL_COUNT %d" % len(TRAILS))
lines.append("")
lines.append("/* gbk_trail_index[trail] -> column index, or -1 when the trail byte is invalid */")
trail_lookup = [-1] * 256
for idx, t in enumerate(TRAILS):
    trail_lookup[t] = idx
lines.append("static const int8_t gbk_trail_index[256] = {")
for base in range(0, 256, 16):
    chunk = ", ".join("%3d" % v for v in trail_lookup[base:base + 16])
    lines.append("    " + chunk + ",")
lines.append("};")
lines.append("")
lines.append("/* gbk_uni[lead - 0x81][gbk_trail_index[trail]] -> unicode, 0xFFFF = unmapped */")
lines.append("static const uint16_t gbk_uni[%d][%d] = {" % (len(rows), len(TRAILS)))
for lead, cells in rows:
    parts = ", ".join("0x%04X" % c for c in cells)
    lines.append("    { %s }, /* 0x%02X */" % (parts, lead))
lines.append("};")
lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))

print("wrote %s : %d mappings, %d leads x %d trails" % (OUT, count, len(rows), len(TRAILS)))
